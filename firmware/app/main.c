/*
 * STM32 Nucleo-L432KC application skeleton: MPU-6050 over I2C1 -> framed
 * samples over USART2 (ST-LINK virtual COM port), 115200 baud, ~100 Hz.
 *
 * !!! NOT COMPILED FOR THE TARGET, NEVER RUN ON HARDWARE !!!
 * This file needs the STM32L4 HAL and the CubeMX-generated init code, neither
 * of which is in this repo. Only protocol/ and drivers/ are compiled and
 * unit-tested (on a PC with gcc, see ../tests).
 *
 * How to use:
 *   1. In STM32CubeIDE create a project for NUCLEO-L432KC and in CubeMX enable
 *      - I2C1 (Standard 100 kHz or Fast 400 kHz), e.g. PB6 = SCL, PB7 = SDA
 *        (check pin choice and solder bridges in the Nucleo-32 user manual),
 *      - USART2 asynchronous, 115200 8N1 (PA2 TX / PA15 RX go to the ST-LINK VCP),
 *      - clock tree as you like (HAL_GetTick needs SysTick at 1 kHz, the default).
 *   2. Let CubeMX generate code. SystemClock_Config, MX_GPIO_Init,
 *      MX_I2C1_Init, MX_USART2_UART_Init, Error_Handler and the hi2c1/huart2
 *      handles come from that generated code, NOT from this file.
 *   3. Add ../protocol/frame.c and ../drivers/mpu6050.c (and their include
 *      paths) to the project, then copy the parts below into the matching
 *      USER CODE sections of the generated main.c.
 */
#include "main.h"      /* generated by CubeMX, pulls in stm32l4xx_hal.h */
#include "frame.h"
#include "mpu6050.h"

/* Defined in the CubeMX-generated main.c / init code. */
extern I2C_HandleTypeDef hi2c1;
extern UART_HandleTypeDef huart2;
void SystemClock_Config(void);
void MX_GPIO_Init(void);
void MX_I2C1_Init(void);
void MX_USART2_UART_Init(void);
void Error_Handler(void);

/* USER CODE BEGIN PV */
#define SAMPLE_PERIOD_MS   10u   /* 100 Hz */
#define I2C_TIMEOUT_MS     5u
#define UART_TIMEOUT_MS    5u    /* 18 bytes at 115200 baud take ~1.6 ms */

static mpu6050_t imu;
static uint8_t seq;
/* USER CODE END PV */

/* USER CODE BEGIN 0 */
/* I2C callbacks for the driver. HAL expects the 7-bit address shifted left. */
static int hal_i2c_write(void *ctx, uint8_t addr, uint8_t reg,
                         const uint8_t *data, size_t len)
{
    I2C_HandleTypeDef *h = (I2C_HandleTypeDef *)ctx;
    /* HAL takes a non-const pointer but does not modify the data on write. */
    return HAL_I2C_Mem_Write(h, (uint16_t)(addr << 1), reg, I2C_MEMADD_SIZE_8BIT,
                             (uint8_t *)data, (uint16_t)len, I2C_TIMEOUT_MS) == HAL_OK ? 0 : -1;
}

static int hal_i2c_read(void *ctx, uint8_t addr, uint8_t reg,
                        uint8_t *data, size_t len)
{
    I2C_HandleTypeDef *h = (I2C_HandleTypeDef *)ctx;
    return HAL_I2C_Mem_Read(h, (uint16_t)(addr << 1), reg, I2C_MEMADD_SIZE_8BIT,
                            data, (uint16_t)len, I2C_TIMEOUT_MS) == HAL_OK ? 0 : -1;
}

static void send_sample(const mpu6050_raw_t *s)
{
    int16_t v[6];
    uint8_t payload[IMU_PAYLOAD_LEN];
    uint8_t frame[IMU_FRAME_LEN];
    size_t n;

    v[0] = s->ax; v[1] = s->ay; v[2] = s->az;
    v[3] = s->gx; v[4] = s->gy; v[5] = s->gz;
    imu_payload_pack(v, payload, sizeof payload);
    n = frame_encode(seq, payload, IMU_PAYLOAD_LEN, frame, sizeof frame);
    if (n > 0) {
        /* Blocking transmit is fine at 18 bytes / 10 ms. Next step: use
         * HAL_UART_Transmit_DMA with a double buffer so the loop never blocks
         * on the UART (then the frame buffer must outlive this function). */
        (void)HAL_UART_Transmit(&huart2, frame, (uint16_t)n, UART_TIMEOUT_MS);
    }
    /* seq increments per sample period, wraps at 255. A failed I2C read below
     * also advances seq, so the host counts it as a lost frame. */
}
/* USER CODE END 0 */

int main(void)
{
    HAL_Init();
    SystemClock_Config();
    MX_GPIO_Init();
    MX_I2C1_Init();
    MX_USART2_UART_Init();

    /* USER CODE BEGIN 2 */
    {
        const mpu6050_bus_t bus = { hal_i2c_write, hal_i2c_read, &hi2c1 };
        HAL_Delay(100);  /* MPU-6050 start-up time after power-on */
        if (mpu6050_init(&imu, &bus, MPU6050_ADDR_AD0_LOW) != MPU6050_OK) {
            Error_Handler();  /* wrong WHO_AM_I or no ACK: check wiring/address */
        }
    }
    uint32_t next = HAL_GetTick();
    /* USER CODE END 2 */

    while (1) {
        /* USER CODE BEGIN 3 */
        /* Unsigned subtraction keeps this correct across the 32-bit tick wrap. */
        if ((int32_t)(HAL_GetTick() - next) >= 0) {
            mpu6050_raw_t s;
            next += SAMPLE_PERIOD_MS;
            if (mpu6050_read_raw(&imu, &s) == MPU6050_OK) {
                send_sample(&s);
            }
            seq++;  /* uint8_t: wraps 255 -> 0, matches the parser */
        }
        /* USER CODE END 3 */
    }
}
